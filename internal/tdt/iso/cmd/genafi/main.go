// Command genafi generates the ISO/IEC 15961-2 data construct table from
// registry.json. It reads that file only and performs no network access.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type registry struct {
	Source struct {
		Document           string `json:"document"`
		Authority          string `json:"authority"`
		AssignmentsEdition string `json:"assignmentsEdition"`
		AssignmentsURL     string `json:"assignmentsURL"`
		ConstructsEdition  string `json:"constructsEdition"`
		ConstructsURL      string `json:"constructsURL"`
	} `json:"source"`
	Constructs []struct {
		AFI             string `json:"afi"`
		Role            string `json:"role"`
		Encoding        string `json:"encoding"`
		Historical      bool   `json:"historical"`
		Supported       bool   `json:"supported"`
		DataIdentifiers []struct {
			DI          string `json:"di"`
			OID         string `json:"oid"`
			OIDConflict string `json:"oidConflict"`
			OIDNote     string `json:"oidNote"`
		} `json:"dataIdentifiers"`
	} `json:"constructs"`
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "genafi:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	dir := filepath.Join(root, "internal", "tdt", "iso")
	body, err := os.ReadFile(filepath.Join(dir, "registry.json"))
	if err != nil {
		return err
	}
	var reg registry
	if err := json.Unmarshal(body, &reg); err != nil {
		return err
	}
	sort.Slice(reg.Constructs, func(i, j int) bool { return reg.Constructs[i].AFI < reg.Constructs[j].AFI })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genafi; DO NOT EDIT.\n\npackage iso\n\n")
	fmt.Fprintf(&b, "// RegisterSource identifies the register edition these constructs come from.\n")
	fmt.Fprintf(&b, "var RegisterSource = Source{\n\tDocument: %q,\n\tAuthority: %q,\n\tAssignmentsEdition: %q,\n\tAssignmentsURL: %q,\n\tConstructsEdition: %q,\n\tConstructsURL: %q,\n}\n\n",
		reg.Source.Document, reg.Source.Authority, reg.Source.AssignmentsEdition,
		reg.Source.AssignmentsURL, reg.Source.ConstructsEdition, reg.Source.ConstructsURL)
	fmt.Fprintf(&b, "// constructs is the registered data construct for each assigned AFI.\nvar constructs = []Construct{\n")
	for _, c := range reg.Constructs {
		afi, err := strconv.ParseUint(strings.TrimPrefix(c.AFI, "0x"), 16, 8)
		if err != nil {
			return fmt.Errorf("AFI %q: %w", c.AFI, err)
		}
		fmt.Fprintf(&b, "\t{\n\t\tAFI: 0x%02X,\n\t\tRole: %q,\n\t\tEncoding: %q,\n\t\tHistorical: %t,\n\t\tSupported: %t,\n",
			afi, c.Role, c.Encoding, c.Historical, c.Supported)
		fmt.Fprintf(&b, "\t\tDataIdentifiers: []DataIdentifier{\n")
		for _, di := range c.DataIdentifiers {
			fmt.Fprintf(&b, "\t\t\t{DI: %q, OID: %q, OIDConflict: %q, OIDNote: %q},\n",
				di.DI, di.OID, di.OIDConflict, di.OIDNote)
		}
		fmt.Fprintf(&b, "\t\t},\n\t},\n")
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "registry_gen.go"), src, 0o644)
}
