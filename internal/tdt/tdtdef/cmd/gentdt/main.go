// Command gentdt generates Go scheme metadata from the vendored GS1 TDT
// artefacts. It reads only the files listed in artefacts.lock.json, verifies
// their digests and declared TDS version, and never performs network access.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// schemes lists the baseline the v2.0.0 support commitment covers. Metadata
// availability upstream is not a support commitment: adding a scheme here is a
// deliberate change that also needs golden vectors.
var schemes = []string{"SGTIN-96", "SSCC-96", "GIAI-96", "GRAI-96"}

type lock struct {
	Repo       string `json:"repo"`
	Commit     string `json:"commit"`
	TDSVersion string `json:"tdsVersion"`
	License    string `json:"license"`
	Files      []struct {
		Path   string `json:"path"`
		SHA256 string `json:"sha256"`
	} `json:"files"`
}

type artefact struct {
	Root struct {
		Version       string `json:"version"`
		Date          string `json:"date"`
		EPCTDSVersion string `json:"epcTDSVersion"`
		Scheme        struct {
			Name      string `json:"name"`
			OptionKey string `json:"optionKey"`
			TagLength int    `json:"tagLength"`
			Level     []struct {
				Type        string `json:"type"`
				PrefixMatch string `json:"prefixMatch"`
				Option      []struct {
					OptionKey string `json:"optionKey"`
					Pattern   string `json:"pattern"`
					Grammar   string `json:"grammar"`
					Field     []struct {
						Seq            int    `json:"seq"`
						Name           string `json:"name"`
						BitLength      int    `json:"bitLength"`
						Length         *int   `json:"length"`
						PadChar        string `json:"padChar"`
						PadDir         string `json:"padDir"`
						CharacterSet   string `json:"characterSet"`
						DecimalMinimum string `json:"decimalMinimum"`
						DecimalMaximum string `json:"decimalMaximum"`
					} `json:"field"`
				} `json:"option"`
			} `json:"level"`
		} `json:"scheme"`
	} `json:"tdt:epcTagDataTranslation"`
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "gentdt:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	dir := filepath.Join(root, "internal", "tdt", "tdtdef")
	artefactDir := filepath.Join(dir, "artefacts")

	lk, err := readLock(filepath.Join(artefactDir, "artefacts.lock.json"))
	if err != nil {
		return err
	}
	digests := make(map[string]string, len(lk.Files))
	for _, f := range lk.Files {
		digests[f.Path] = f.SHA256
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gentdt; DO NOT EDIT.\n\npackage tdtdef\n\n")
	fmt.Fprintf(&out, "// Schemes holds the generated EPC tag encoding scheme definitions.\nvar Schemes = []Scheme{\n")

	var patterns []patternVector
	for _, name := range schemes {
		file := name + ".json"
		body, err := readVerified(filepath.Join(artefactDir, file), digests[file])
		if err != nil {
			return err
		}
		var a artefact
		if err := json.Unmarshal(body, &a); err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		if got := a.Root.EPCTDSVersion; got != lk.TDSVersion {
			return fmt.Errorf("%s declares TDS version %q, lock pins %q: artefact skew must be resolved deliberately", file, got, lk.TDSVersion)
		}
		s, pv, err := convert(a)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		patterns = append(patterns, pv...)
		writeScheme(&out, s)
	}
	fmt.Fprintf(&out, "}\n")

	if err := writeGo(filepath.Join(dir, "schemes_gen.go"), out.Bytes()); err != nil {
		return err
	}
	if err := writeProvenance(filepath.Join(dir, "provenance_gen.go"), lk); err != nil {
		return err
	}
	return writePatterns(filepath.Join(dir, "testdata", "binary_patterns.json"), patterns)
}

// patternVector carries an upstream regular expression so tests can check the
// generated bit layout against the artefact. Regular expressions never reach
// the runtime decode path.
type patternVector struct {
	Scheme    string `json:"scheme"`
	GCPLength int    `json:"gcpLength"`
	Pattern   string `json:"pattern"`
}

type scheme struct {
	Name          string
	TagLength     int
	Header        uint64
	HeaderBits    int
	TagURIPrefix  string
	PureURIPrefix string
	Options       []option
}

type option struct {
	GCPLength      int
	Partition      int
	BinaryFields   []binaryField
	BinaryLiterals []binaryLiteral
	TagFields      []uriField
	PureFields     []uriField
}

type binaryField struct {
	Name       string
	BitOffset  int
	BitLength  int
	DecimalMax uint64
}

type binaryLiteral struct {
	BitOffset int
	BitLength int
	Value     uint64
}

type uriField struct {
	Name         string
	Length       int
	Fixed        bool
	PadChar      byte
	PadDir       string
	CharacterSet string
	DecimalMax   uint64
}

func convert(a artefact) (scheme, []patternVector, error) {
	s := scheme{Name: a.Root.Scheme.Name, TagLength: a.Root.Scheme.TagLength}
	if a.Root.Scheme.OptionKey != "gs1companyprefixlength" {
		return s, nil, fmt.Errorf("unsupported optionKey %q", a.Root.Scheme.OptionKey)
	}

	byType := map[string]int{}
	for i, lv := range a.Root.Scheme.Level {
		byType[lv.Type] = i
	}
	for _, want := range []string{"BINARY", "TAG_ENCODING", "PURE_IDENTITY"} {
		if _, ok := byType[want]; !ok {
			return s, nil, fmt.Errorf("missing %s level", want)
		}
	}

	binary := a.Root.Scheme.Level[byType["BINARY"]]
	tagLevel := a.Root.Scheme.Level[byType["TAG_ENCODING"]]
	pureLevel := a.Root.Scheme.Level[byType["PURE_IDENTITY"]]

	header, err := strconv.ParseUint(binary.PrefixMatch, 2, 64)
	if err != nil {
		return s, nil, fmt.Errorf("header %q: %w", binary.PrefixMatch, err)
	}
	s.Header = header
	s.HeaderBits = len(binary.PrefixMatch)
	s.TagURIPrefix = tagLevel.PrefixMatch + ":"
	s.PureURIPrefix = pureLevel.PrefixMatch + ":"

	var vectors []patternVector
	for i, bo := range binary.Option {
		gcp, err := strconv.Atoi(bo.OptionKey)
		if err != nil {
			return s, nil, fmt.Errorf("optionKey %q: %w", bo.OptionKey, err)
		}
		maxima := decimalMaxima(bo.Field)
		bits := map[string]int{}
		for _, f := range bo.Field {
			bits[f.Name] = f.BitLength
		}

		opt := option{GCPLength: gcp, Partition: -1}
		offset := 0
		prevLiteral := -1
		for _, tok := range tokens(bo.Grammar) {
			if tok.literal {
				value, err := strconv.ParseUint(tok.text, 2, 64)
				if err != nil {
					return s, nil, fmt.Errorf("literal %q: %w", tok.text, err)
				}
				opt.BinaryLiterals = append(opt.BinaryLiterals, binaryLiteral{
					BitOffset: offset, BitLength: len(tok.text), Value: value,
				})
				prevLiteral = len(opt.BinaryLiterals) - 1
				offset += len(tok.text)
				continue
			}
			width, ok := bits[tok.text]
			if !ok || width == 0 {
				return s, nil, fmt.Errorf("field %q has no bitLength", tok.text)
			}
			if tok.text == "gs1companyprefix" && prevLiteral >= 0 {
				opt.Partition = int(opt.BinaryLiterals[prevLiteral].Value)
			}
			opt.BinaryFields = append(opt.BinaryFields, binaryField{
				Name: tok.text, BitOffset: offset, BitLength: width, DecimalMax: maxima[tok.text],
			})
			offset += width
			prevLiteral = -1
		}
		if offset != s.TagLength {
			return s, nil, fmt.Errorf("option %d: layout covers %d bits, tag length is %d", gcp, offset, s.TagLength)
		}
		if opt.Partition < 0 {
			return s, nil, fmt.Errorf("option %d: no partition literal precedes gs1companyprefix", gcp)
		}
		// The upstream artefacts encode the partition only as literal bits.
		// Cross-check it against the GCP length so a silent upstream reshuffle
		// cannot slip through generation unnoticed.
		if want := 12 - gcp; opt.Partition != want {
			return s, nil, fmt.Errorf("option %d: partition %d, expected %d", gcp, opt.Partition, want)
		}

		if opt.TagFields, err = uriFields(tagLevel.Option[i], gcp, s.TagURIPrefix); err != nil {
			return s, nil, fmt.Errorf("tag option %d: %w", gcp, err)
		}
		if opt.PureFields, err = uriFields(pureLevel.Option[i], gcp, s.PureURIPrefix); err != nil {
			return s, nil, fmt.Errorf("pure option %d: %w", gcp, err)
		}
		s.Options = append(s.Options, opt)
		vectors = append(vectors, patternVector{Scheme: s.Name, GCPLength: gcp, Pattern: bo.Pattern})
	}
	sort.Slice(s.Options, func(i, j int) bool { return s.Options[i].GCPLength < s.Options[j].GCPLength })
	sort.Slice(vectors, func(i, j int) bool { return vectors[i].GCPLength < vectors[j].GCPLength })
	return s, vectors, nil
}

func uriFields(opt struct {
	OptionKey string `json:"optionKey"`
	Pattern   string `json:"pattern"`
	Grammar   string `json:"grammar"`
	Field     []struct {
		Seq            int    `json:"seq"`
		Name           string `json:"name"`
		BitLength      int    `json:"bitLength"`
		Length         *int   `json:"length"`
		PadChar        string `json:"padChar"`
		PadDir         string `json:"padDir"`
		CharacterSet   string `json:"characterSet"`
		DecimalMinimum string `json:"decimalMinimum"`
		DecimalMaximum string `json:"decimalMaximum"`
	} `json:"field"`
}, gcp int, prefix string) ([]uriField, error) {
	if key, err := strconv.Atoi(opt.OptionKey); err != nil || key != gcp {
		return nil, fmt.Errorf("optionKey %q does not align with %d", opt.OptionKey, gcp)
	}
	byName := map[string]int{}
	for i, f := range opt.Field {
		byName[f.Name] = i
	}
	var out []uriField
	first := true
	for _, tok := range tokens(opt.Grammar) {
		if tok.literal {
			switch {
			case first && tok.text == strings.TrimSuffix(prefix, ":")+":":
			case !first && tok.text == ".":
			default:
				return nil, fmt.Errorf("unexpected literal %q", tok.text)
			}
			first = false
			continue
		}
		first = false
		i, ok := byName[tok.text]
		if !ok {
			return nil, fmt.Errorf("unknown field %q", tok.text)
		}
		f := opt.Field[i]
		var pad byte
		if f.PadChar != "" {
			pad = f.PadChar[0]
		}
		length, fixed := 0, false
		if f.Length != nil {
			length, fixed = *f.Length, true
		}
		if f.DecimalMaximum == "" {
			return nil, fmt.Errorf("field %q has no decimalMaximum", f.Name)
		}
		out = append(out, uriField{
			Name:         f.Name,
			Length:       length,
			Fixed:        fixed,
			PadChar:      pad,
			PadDir:       f.PadDir,
			CharacterSet: f.CharacterSet,
			DecimalMax:   parseUint(f.DecimalMaximum),
		})
	}
	return out, nil
}

func decimalMaxima(fields []struct {
	Seq            int    `json:"seq"`
	Name           string `json:"name"`
	BitLength      int    `json:"bitLength"`
	Length         *int   `json:"length"`
	PadChar        string `json:"padChar"`
	PadDir         string `json:"padDir"`
	CharacterSet   string `json:"characterSet"`
	DecimalMinimum string `json:"decimalMinimum"`
	DecimalMaximum string `json:"decimalMaximum"`
}) map[string]uint64 {
	out := make(map[string]uint64, len(fields))
	for _, f := range fields {
		out[f.Name] = parseUint(f.DecimalMaximum)
	}
	return out
}

func parseUint(s string) uint64 {
	v, err := strconv.ParseUint(s, 10, 64)
	if err != nil {
		return 0
	}
	return v
}

type token struct {
	text    string
	literal bool
}

// tokens splits a TDT grammar string into quoted literals and field names.
func tokens(grammar string) []token {
	var out []token
	for i := 0; i < len(grammar); {
		switch c := grammar[i]; {
		case c == ' ':
			i++
		case c == '\'':
			j := strings.IndexByte(grammar[i+1:], '\'')
			if j < 0 {
				return out
			}
			out = append(out, token{text: grammar[i+1 : i+1+j], literal: true})
			i += j + 2
		default:
			j := strings.IndexByte(grammar[i:], ' ')
			if j < 0 {
				out = append(out, token{text: grammar[i:]})
				return out
			}
			out = append(out, token{text: grammar[i : i+j]})
			i += j
		}
	}
	return out
}

func writeScheme(w *bytes.Buffer, s scheme) {
	fmt.Fprintf(w, "\t{\n\t\tName: %q,\n\t\tTagLength: %d,\n\t\tHeader: 0b%b,\n\t\tHeaderBits: %d,\n",
		s.Name, s.TagLength, s.Header, s.HeaderBits)
	fmt.Fprintf(w, "\t\tTagURIPrefix: %q,\n\t\tPureURIPrefix: %q,\n\t\tOptions: []Option{\n", s.TagURIPrefix, s.PureURIPrefix)
	for _, o := range s.Options {
		fmt.Fprintf(w, "\t\t\t{\n\t\t\t\tGCPLength: %d,\n\t\t\t\tPartition: %d,\n", o.GCPLength, o.Partition)
		fmt.Fprintf(w, "\t\t\t\tBinaryFields: []BinaryField{\n")
		for _, f := range o.BinaryFields {
			fmt.Fprintf(w, "\t\t\t\t\t{Name: %q, BitOffset: %d, BitLength: %d, DecimalMax: %d},\n",
				f.Name, f.BitOffset, f.BitLength, f.DecimalMax)
		}
		fmt.Fprintf(w, "\t\t\t\t},\n\t\t\t\tBinaryLiterals: []BinaryLiteral{\n")
		for _, l := range o.BinaryLiterals {
			fmt.Fprintf(w, "\t\t\t\t\t{BitOffset: %d, BitLength: %d, Value: 0b%b},\n", l.BitOffset, l.BitLength, l.Value)
		}
		fmt.Fprintf(w, "\t\t\t\t},\n")
		writeURIFields(w, "TagFields", o.TagFields)
		writeURIFields(w, "PureFields", o.PureFields)
		fmt.Fprintf(w, "\t\t\t},\n")
	}
	fmt.Fprintf(w, "\t\t},\n\t},\n")
}

func writeURIFields(w *bytes.Buffer, name string, fields []uriField) {
	fmt.Fprintf(w, "\t\t\t\t%s: []URIField{\n", name)
	for _, f := range fields {
		pad := "PadNone"
		switch f.PadDir {
		case "LEFT":
			pad = "PadLeft"
		case "RIGHT":
			pad = "PadRight"
		}
		fmt.Fprintf(w, "\t\t\t\t\t{Name: %q, Length: %d, Fixed: %t, PadChar: %q, PadDir: %s, CharacterSet: %q, DecimalMax: %d},\n",
			f.Name, f.Length, f.Fixed, f.PadChar, pad, f.CharacterSet, f.DecimalMax)
	}
	fmt.Fprintf(w, "\t\t\t\t},\n")
}

func writeProvenance(path string, lk lock) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gentdt; DO NOT EDIT.\n\npackage tdtdef\n\n")
	fmt.Fprintf(&b, "// Source describes the pinned upstream artefacts these definitions came from.\n")
	fmt.Fprintf(&b, "type Source struct {\n\tRepo string\n\tCommit string\n\tTDSVersion string\n\tLicense string\n\tFiles []SourceFile\n}\n\n")
	fmt.Fprintf(&b, "// SourceFile is one vendored artefact and its content digest.\ntype SourceFile struct {\n\tPath string\n\tSHA256 string\n}\n\n")
	fmt.Fprintf(&b, "// Provenance is the pinned artefact provenance for this build.\nvar Provenance = Source{\n")
	fmt.Fprintf(&b, "\tRepo: %q,\n\tCommit: %q,\n\tTDSVersion: %q,\n\tLicense: %q,\n\tFiles: []SourceFile{\n", lk.Repo, lk.Commit, lk.TDSVersion, lk.License)
	for _, f := range lk.Files {
		fmt.Fprintf(&b, "\t\t{Path: %q, SHA256: %q},\n", f.Path, f.SHA256)
	}
	fmt.Fprintf(&b, "\t},\n}\n")
	return writeGo(path, b.Bytes())
}

func writePatterns(path string, vectors []patternVector) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	body, err := json.MarshalIndent(vectors, "", "\t")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(body, '\n'), 0o644)
}

func writeGo(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func readLock(path string) (lock, error) {
	var lk lock
	body, err := os.ReadFile(path)
	if err != nil {
		return lk, err
	}
	err = json.Unmarshal(body, &lk)
	return lk, err
}

func readVerified(path, want string) ([]byte, error) {
	body, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(body)
	if got := hex.EncodeToString(sum[:]); got != want {
		return nil, fmt.Errorf("%s: digest %s does not match lock %s", filepath.Base(path), got, want)
	}
	return body, nil
}
